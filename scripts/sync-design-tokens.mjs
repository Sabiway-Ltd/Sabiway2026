import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "design-system", "tokens.json");
const tokens = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const banner = "// AUTO-GENERATED by scripts/sync-design-tokens.mjs. Edit design-system/tokens.json instead.\n";

const ts = `${banner}export const designTokens = ${JSON.stringify(tokens, null, 2)} as const;\n`;
const mobileTs = `${banner}export const designTokens = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport const colors = designTokens.semantic.color.light;\nexport const spacing = designTokens.spacing;\nexport const radius = designTokens.radius;\nexport const typography = designTokens.typography;\nexport const interaction = designTokens.interaction;\n`;

const light = tokens.semantic.color.light;
const dark = tokens.semantic.color.dark;
const cssVars = (values, prefix = "--sabi") => Object.entries(values).map(([key, value]) => `  ${prefix}-${key.replace(/[A-Z]/g, m => `-${m.toLowerCase()}`)}: ${typeof value === "number" ? `${value}px` : value};`).join("\n");

const css = `/* AUTO-GENERATED by scripts/sync-design-tokens.mjs. Edit design-system/tokens.json instead. */\n:root {\n${cssVars(light)}\n  --sabi-font-family: ${tokens.typography.fontFamily}, ui-sans-serif, system-ui, sans-serif;\n${cssVars(tokens.spacing, "--sabi-space")}\n${cssVars(tokens.radius, "--sabi-radius")}\n  --sabi-shadow-sm: ${tokens.elevation.sm};\n  --sabi-shadow-md: ${tokens.elevation.md};\n  --sabi-shadow-lg: ${tokens.elevation.lg};\n  --sabi-touch-target: ${tokens.interaction.minimumTouchTarget}px;\n  --sabi-focus-ring-width: ${tokens.interaction.focusRingWidth}px;\n}\n\n.dark {\n${cssVars(dark)}\n}\n`;

const outputs = new Map([
  ["frontend/app/design/tokens.ts", ts],
  ["mobile/src/design/tokens.ts", mobileTs],
  ["frontend/app/design/tokens.css", css],
]);

const check = process.argv.includes("--check");
let drift = false;
for (const [relative, content] of outputs) {
  const output = path.join(root, relative);
  if (check) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== content) {
      console.error(`Design-token drift: ${relative}`);
      drift = true;
    }
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, content);
    console.log(`Synced ${relative}`);
  }
}
if (drift) process.exit(1);
